"""
Critic agent for Jahiv - validates responses for hallucinations, relevance, and completeness.
"""

import json
import logging
import re
from typing import Any, Dict, Optional, Union

import httpx

from app.config import settings

logger = logging.getLogger("jahiv.critic")

CRITIC_SYSTEM = (
    "You are the Critic agent. Your job is to review a draft answer for quality.\n\n"
    "Check for:\n"
    "1. Hallucination — does it claim facts not present in the document context?\n"
    "2. Relevance — does it actually address the user query?\n"
    "3. Completeness — is anything important missing from the context?\n\n"
    "Respond in this EXACT format:\n"
    "VERDICT: PASS or FAIL\n"
    "ISSUES: brief description of problems, or NONE\n"
    "IMPROVED_ANSWER: improved version if FAIL, or SAME if PASS\n"
)


async def _call_ollama(prompt: str) -> str:
    """Call Ollama generate API asynchronously with a 120-second timeout."""
    async with httpx.AsyncClient(timeout=120.0) as client:
        response = await client.post(
            f"{settings.OLLAMA_BASE_URL}/api/generate",
            json={"model": settings.LLM_MODEL, "prompt": prompt, "stream": False},
        )
        if response.status_code != 200:
            err_msg = response.text
            try:
                err_msg = response.json().get("error", response.text)
            except Exception:
                pass
            raise RuntimeError(
                f"Ollama error ({response.status_code}): {err_msg}. "
                f"Verify '{settings.LLM_MODEL}' is pulled (run 'ollama list')."
            )
        return response.json().get("response", "")


async def critique_response(
    question: str,
    draft_answer: str,
    tool_results: Optional[Union[Dict[str, Any], str]] = None,
) -> Dict[str, Any]:
    """
    Critique a draft answer against retrieved context.

    Args:
        question: User query.
        draft_answer: Draft answer generated by the executor.
        tool_results: Retrieved context / tool outputs used for drafting.

    Returns:
        Dict with verdict, issues, final_answer, and raw_review.
    """
    doc_context = ""
    if isinstance(tool_results, dict) and tool_results.get("retriever"):
        doc_context = f"[Document context used]\n{tool_results['retriever']}\n\n"
    elif isinstance(tool_results, str) and tool_results:
        doc_context = f"[Document context used]\n{tool_results}\n\n"

    prompt = (
        CRITIC_SYSTEM
        + "\n\n"
        + doc_context
        + f"USER QUERY: {question}\n\n"
        + f"DRAFT ANSWER:\n{draft_answer}\n\n"
        + "Your review:"
    )

    try:
        raw = await _call_ollama(prompt)
    except Exception as exc:
        logger.warning(f"Critic LLM call failed: {exc}. Defaulting to draft answer.")
        return {
            "verdict": "PASS",
            "issues": f"Critic call skipped due to error: {exc}",
            "final_answer": draft_answer,
            "raw_review": "",
        }

    # 1. Attempt JSON parsing if output was formatted as JSON
    try:
        json_candidate = raw.strip()
        if "```json" in json_candidate:
            json_candidate = json_candidate.split("```json")[1].split("```")[0].strip()
        elif "```" in json_candidate:
            json_candidate = json_candidate.split("```")[1].split("```")[0].strip()

        if json_candidate.startswith("{") and json_candidate.endswith("}"):
            parsed = json.loads(json_candidate)
            if isinstance(parsed, dict):
                verdict = str(parsed.get("verdict", "PASS")).upper()
                issues = str(parsed.get("issues", "NONE"))
                improved = str(
                    parsed.get("improved_answer", parsed.get("final_answer", "SAME"))
                ).strip()
                if improved.upper() == "SAME" or verdict == "PASS":
                    final_answer = draft_answer
                else:
                    final_answer = improved
                return {
                    "verdict": verdict,
                    "issues": issues,
                    "final_answer": final_answer,
                    "raw_review": raw,
                }
    except Exception:
        # Fall through to regex parsing
        pass

    # 2. Parse standard prompt template format via regex
    try:
        verdict_match = re.search(r"VERDICT:\s*(\w+)", raw, re.IGNORECASE)
        verdict = verdict_match.group(1).upper() if verdict_match else "PASS"

        improved_match = re.search(r"IMPROVED_ANSWER:\s*([\s\S]+)", raw, re.IGNORECASE)
        if improved_match:
            improved = improved_match.group(1).strip()
            if improved.upper() == "SAME" or verdict == "PASS":
                final_answer = draft_answer
            else:
                final_answer = improved
        else:
            final_answer = draft_answer

        issues_match = re.search(r"ISSUES:\s*(.+)", raw, re.IGNORECASE)
        issues = issues_match.group(1).strip() if issues_match else "NONE"

        return {
            "verdict": verdict,
            "issues": issues,
            "final_answer": final_answer,
            "raw_review": raw,
        }
    except Exception as exc:
        logger.warning(f"Critic parse failed: {exc}. Defaulting to draft answer.")
        # Fallback on parse failure
        return {
            "verdict": "PASS",
            "issues": "NONE",
            "final_answer": draft_answer,
            "raw_review": raw,
        }


# Backwards compatibility alias
async def run_critic(
    user_query: str,
    draft_answer: str,
    tool_results: Any,
) -> Dict[str, Any]:
    return await critique_response(
        question=user_query,
        draft_answer=draft_answer,
        tool_results=tool_results,
    )
