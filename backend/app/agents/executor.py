"""
Executor agent for Jahiv - synthesizes tool results and conversation context into answers.
"""

import logging
from typing import Any, Dict, List, Optional, Union

import httpx

from app.config import settings

logger = logging.getLogger("jahiv.executor")

EXECUTOR_SYSTEM = (
    "You are the Executor agent. Your job is to synthesise tool results and\n"
    "conversation context into a clear, accurate, helpful answer.\n\n"
    "Rules:\n"
    "- Answer ONLY from the provided context and tool results.\n"
    "- If the document context does not contain the answer, say so honestly.\n"
    "- Do NOT make up facts or figures.\n"
    "- Always cite sources using the exact format [filename p.N] (e.g. [document.pdf p.3]).\n"
    "- Be concise and direct.\n"
)


async def _call_ollama(prompt: str) -> str:
    """Call Ollama generate API asynchronously with a 120-second timeout."""
    async with httpx.AsyncClient(timeout=120.0) as client:
        response = await client.post(
            f"{settings.OLLAMA_BASE_URL}/api/generate",
            json={"model": settings.LLM_MODEL, "prompt": prompt, "stream": False},
        )
        if response.status_code != 200:
            err_msg = response.text
            try:
                err_msg = response.json().get("error", response.text)
            except Exception:
                pass
            raise RuntimeError(
                f"Ollama error ({response.status_code}): {err_msg}. "
                f"Verify '{settings.LLM_MODEL}' is pulled (run 'ollama list')."
            )
        return response.json().get("response", "")


async def generate_response(
    question: str,
    tool_results: Optional[Union[Dict[str, Any], str]] = None,
    plan: Optional[Union[Dict[str, Any], str]] = None,
    conversation_history: Optional[List[Dict[str, str]]] = None,
    rolling_summary: Optional[str] = None,
) -> str:
    """
    Synthesize tool results and conversation history into an answer with citations.

    Args:
        question: User query.
        tool_results: Output from executed tools (e.g., retriever, calculator).
        plan: Plan notes or dictionary generated by the planner.
        conversation_history: List of recent conversation turns.
        rolling_summary: Rolling summary of older conversation history.

    Returns:
        Grounded answer with [filename p.N] citations.
    """
    context_block = ""

    if rolling_summary:
        context_block += f"[Conversation history summary]\n{rolling_summary}\n\n"

    if conversation_history:
        context_block += "[Recent conversation]\n"
        for m in conversation_history[-6:]:
            role = m.get("role", "user").upper()
            content = m.get("content", "")
            context_block += f"{role}: {content}\n"
        context_block += "\n"

    if tool_results:
        context_block += "[Tool results]\n"
        if isinstance(tool_results, dict):
            for tool_name, result in tool_results.items():
                context_block += f"Tool: {tool_name}\n{result}\n\n"
        elif isinstance(tool_results, list):
            for item in tool_results:
                context_block += f"{item}\n\n"
        else:
            context_block += f"{tool_results}\n\n"

    plan_str = ""
    if isinstance(plan, dict):
        plan_str = plan.get("plan", str(plan))
    elif isinstance(plan, str):
        plan_str = plan

    plan_block = f"[Planner notes]\n{plan_str}\n\n" if plan_str else ""

    prompt = (
        EXECUTOR_SYSTEM
        + "\n\n"
        + context_block
        + plan_block
        + f"USER QUERY: {question}\n\n"
        + "Your answer:"
    )

    try:
        return await _call_ollama(prompt)
    except Exception as exc:
        logger.error(f"Executor LLM call failed: {exc}")
        return f"Unable to generate response due to LLM error: {exc}"


# Backwards compatibility alias
async def run_executor(
    user_query: str,
    plan_output: Any,
    tool_results: Any,
    long_term_summary: Optional[str] = None,
    recent_turns: Optional[List[Dict[str, str]]] = None,
    tools: Any = None,
) -> str:
    return await generate_response(
        question=user_query,
        tool_results=tool_results,
        plan=plan_output,
        conversation_history=recent_turns,
        rolling_summary=long_term_summary,
    )
